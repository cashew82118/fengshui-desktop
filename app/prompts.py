FEATURE_LABEL = {k: label for k, label, _n, _v in FEATURES}
NEEDS_BIRTH = {k for k, _l, need, _v in FEATURES if need}
VARIANT_N = 3


def compose(feature: str, variant: int = 0, date: str | None = None) -> str:
    """拼出一整篇：开头 + 主体 + 结尾。未知功能退回「布局体检」。"""
    body = None
    for key, _label, _need, variants in FEATURES:
        if key == feature:
            body = variants[variant % VARIANT_N]
            break
    if body is None:
        body = FEATURES[5][3][variant % VARIANT_N]
    day = date or datetime.date.today().strftime("%Y-%m-%d")
    return OPEN + "\n\n" + body.replace("{date}", day) + "\n\n" + CLOSE


def variant_of(feature: str) -> int:
    """该功能有几套同义主体（固定 3，供界面显示 1/3）。"""
    return VARIANT_N


def label(feature: str) -> str:
    return FEATURE_LABEL.get(feature, "布局体检")


def needs_birth(feature: str) -> bool:
    return feature in NEEDS_BIRTH
