def pick(key: str, **kw) -> tuple[str, str, str] | None:
    """随机抽一组说法并填模板；该分支还没有池子时返回 None（调用方回落旧文案）。"""
    items = POOL.get(key)
    if not items:
        return None
    ev, pr, ad = random.choice(items)
    try:
        return (ev.format(**kw), pr.format(**kw), ad.format(**kw))
    except (KeyError, IndexError, ValueError):
        return None


def sizes() -> dict[str, int]:
    """各分支现有几组说法（测试用）。"""
    return {k: len(v) for k, v in POOL.items()}
