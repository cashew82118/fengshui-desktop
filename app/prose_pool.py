# ================================================================ 取句

def pick(key: str, idx: int = 0) -> str:
    """按指纹取一条变体。

    不用 random：同一张桌面反复打开必须看到同一版文字。
    「换一版」只在桌面本身变了（图标增删、分布变动）时才发生。
    """
    items = POOL.get(key)
    if not items:
        return ""
    return items[idx % len(items)]


def seed(result: dict) -> int:
    """桌面指纹。同一张盘 → 同一个数 → 同一版文字。"""
    st = result.get("stats", {}) or {}
    h = 17
    for k in ("total", "occupied", "left", "right", "hall", "center"):
        h = h * 31 + int(st.get(k, 0) or 0)
    h = h * 31 + int(result.get("score", 0) or 0)
    return h


def sizes() -> dict[str, int]:
    """各分支现有几条变体（测试用）。"""
    return {k: len(v) for k, v in POOL.items()}
